// Small shared file helpers. The Excel/PDF writers live in reportExport.js.

// Local date (YYYY-MM-DD) for file names. toISOString() is UTC, which gave
// yesterday's date for files exported in India between midnight and 5:30 am.
export function timestamp() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function downloadBlob(blob, fileName) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
